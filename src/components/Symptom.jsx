const FEELING_CHIPS = [
  "Tired", "Foggy brain", "Headache", "Nausea", "Bloated",
  "Anxious", "Can't sleep", "Low mood", "Aching", "Joint pain",
  "No appetite", "Heart palpitations", "Dizziness", "Low energy",
  "Skin issues", "Digestive issues",
];

export default function Symptom({ user, navQuery, onPageContext }) {
  const [feelings, setFeelings] = useState([]);
  const [custom, setCustom] = useState("");
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [showDrNote, setShowDrNote] = useState(false);
  const { voiceName } = useVoicePrefs();
  const { speak, speaking, stopSpeaking } = useVoice(voiceName);

  useEffect(() => {
    if (!navQuery) return;
    setCustom(navQuery.trim());
  }, [navQuery]);

  const analyse = async () => {
    const all = [...feelings, ...(custom.trim() ? [custom.trim()] : [])];
    if (!all.length) return;
    setLoading(true);
    setResult(null);

    const prompt = `You are a compassionate CelerySync companion helping an adult reflect on how they're feeling and find the right official resources.

Person: ${user?.name || "friend"}
How they're feeling / what they're experiencing: ${all.join(", ")}

Be warm and compassionate. Address them by name (${user?.name || "friend"}).

⚠️ HARD RULES — do not break any of these:
- NEVER diagnose, or claim anything treats, cures, heals, or prevents anything.
- NEVER recommend supplements, foods, foods to avoid, protocols, or amounts — not even framed as "Anthony William suggests". This app does not supply protocol content; the person's own books are their source.
- NEVER explain what their feelings "mean" medically or name likely causes (no pathogen, viral, or toxin explanations).
- NEVER advise on prescription medications.
- Use only general-wellbeing framing: "supports", "may help with general wellbeing", rest, hydration, gentle routine.

Provide exactly these sections:

## 💚 What You Shared
Reflect back, in plain warm language, what they said they're experiencing — so they feel heard. Descriptive only.

## ✍️ Worth Tracking
Suggest logging these feelings in the app (energy, mood, notes) so they can watch their own patterns over time and share them with their doctor. Describe — never interpret — trends.

## 📚 Where to Read More
Name which of Anthony William's books or official resources (medicalmedium.com, his podcast/YouTube) cover the topics they raised, so they can go straight to the source. Point to the source only — do not summarise what it says.

## 💛 Encouragement
One warm paragraph acknowledging this person's commitment to their wellbeing. If anything they described sounds severe, worsening, or urgent, gently encourage them to see their doctor promptly.

End with: ⚠️ This is not medical advice — always work with your healthcare provider. Your own copy of Anthony William's books is the source for anything you choose to follow.`;

    try {
      const text = await callClaude({
        tier: 'standard',
        maxTokens: 2000,
        messages: [{ role: "user", content: prompt }],
      });
      setResult(text);
      onPageContext?.({
        tab: 'track',
        label: `Feeling: ${all.join(", ")}`,
        detail: text.slice(0, 600),
      });
    } catch (err) {
      setResult(`Connection error: ${err.message}. Please check your connection and try again.`);
    }
    setLoading(false);
  };

  const toggleFeeling = (f) => {
    setFeelings((p) => p.includes(f) ? p.filter((x) => x !== f) : [...p, f]);
    setResult(null);
  };

  const hasInput = feelings.length > 0 || custom.trim().length > 0;

  return (
    <div style={{ display: "flex", flexDirection: "column", gap: 16 }}>
      <div>
        <h2 style={{ margin: 0, fontFamily: "Georgia,serif", fontSize: 22, color: C.charcoal }}>
          💚 How are you feeling?
        </h2>
        <p style={{ margin: "4px 0 0", fontSize: 13, color: C.mid, fontFamily: "Georgia,serif" }}>
          No diagnosis needed — just describe what's going on for you
        </p>
      </div>

      {/* Quick feeling chips */}
      <div>
        <div style={{ fontSize: 12, color: C.muted, marginBottom: 8, fontFamily: "Georgia,serif" }}>
          Tap what applies to you:
        </div>
        <div style={{ display: "flex", flexWrap: "wrap", gap: 8 }}>
          {FEELING_CHIPS.map((f) => (
            <div
              key={f}
              onClick={() => toggleFeeling(f)}
              style={{
                padding: "8px 16px",
                borderRadius: 30,
                fontSize: 13,
                fontFamily: "Georgia,serif",
                cursor: "pointer",
                border: `2px solid ${feelings.includes(f) ? C.sage : C.border}`,
                background: feelings.includes(f) ? C.sageLight : "transparent",
                color: feelings.includes(f) ? C.sageDark : C.mid,
                fontWeight: feelings.includes(f) ? 700 : 400,
                transition: "all 0.15s",
              }}
            >
              {feelings.includes(f) ? "✓ " : ""}{f}
            </div>
          ))}
        </div>
      </div>

      {/* Free text */}
      <div>
        <div style={{ fontSize: 12, color: C.muted, marginBottom: 6, fontFamily: "Georgia,serif" }}>
          Or describe in your own words:
        </div>
        <textarea
          value={custom}
          onChange={(e) => { setCustom(e.target.value); setResult(null); }}
          placeholder="e.g. tired all the time, foggy head in the mornings, bloated after eating, can't sleep well…"
          rows={3}
          style={{
            width: "100%", boxSizing: "border-box",
            padding: "12px 16px",
            borderRadius: 14,
            border: `1.5px solid ${C.border}`,
            fontFamily: "Georgia,serif",
            fontSize: 13,
            outline: "none",
            background: C.mist,
            resize: "vertical",
            lineHeight: 1.6,
          }}
        />
      </div>

      <Btn full onClick={analyse} disabled={loading || !hasInput} color={C.sage}>
        {loading ? "🌿 Looking into this…" : "🌿 Get Support"}
      </Btn>

      {result !== null && (
        <Card style={{ background: C.mist }}>
          <div style={{
            display: "flex", justifyContent: "space-between",
            alignItems: "center", marginBottom: 10, flexWrap: "wrap", gap: 8,
          }}>
            <div style={{ fontFamily: "Georgia,serif", fontWeight: 700, fontSize: 14, color: C.charcoal }}>
              Support Overview
            </div>
            <div style={{ display: "flex", gap: 7, flexWrap: "wrap" }}>
              <Btn small onClick={() => (speaking ? stopSpeaking() : speak(result))} color={C.sage}>
                {speaking ? "⏹ Stop" : "🔊 Listen"}
              </Btn>
              <Btn small onClick={() => setShowDrNote((v) => !v)} color={C.plum}>
                🩺 Doctor Summary
              </Btn>
            </div>
          </div>

          {showDrNote && (
            <div style={{
              background: "#f0f7f0", border: `1px solid ${C.sage}50`,
              borderRadius: 12, padding: "14px 16px", marginBottom: 12,
            }}>
              <div style={{ fontFamily: "Georgia,serif", fontWeight: 700, fontSize: 13, color: C.sageDark, marginBottom: 8 }}>
                🩺 Doctor / Practitioner Summary
              </div>
              <div style={{ fontSize: 12.5, color: C.mid, lineHeight: 1.6, marginBottom: 12 }}>
                Creates a printable wellness summary with the AI companion's response — perfect to share with your GP or naturopath.
              </div>
              <Btn full color={C.sageDark} onClick={() => printDoctorSummary({ user, result })}>
                🖨 Print / Save as PDF
              </Btn>
            </div>
          )}

          <div style={{ fontSize: 13.5, color: C.charcoal, lineHeight: 1.8, whiteSpace: "pre-wrap" }}>
            {result}
          </div>
        </Card>
      )}

      <div style={{
        background: C.sageLight, border: `1px solid ${C.sage}40`,
        borderRadius: 12, padding: 10, fontSize: 11.5, color: C.sageDark,
      }}>
        📖 Descriptive only — this screen reflects what you share, it never interprets it. Not medical advice — always work with your healthcare provider. Your own copy of Anthony William's books (linked in <strong>Learn</strong>) is the source for anything you follow.
      </div>
    </div>
  );
}
