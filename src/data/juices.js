// Helpers
export function getJuicesByCategory() {
  const all = [...JUICES, ...SHOTS];
  return all.reduce((acc, item) => {
    if (!acc[item.category]) acc[item.category] = [];
    acc[item.category].push(item);
    return acc;
  }, {});
}

export function getCoreProtocol() {
  return JUICES.filter((j) => j.isCore).sort((a, b) => a.coreOrder - b.coreOrder);
}

export function getByType(type) {
  return [...JUICES, ...SHOTS].filter((j) => j.type === type);
}

export function getById(id) {
  return [...JUICES, ...SHOTS].find((j) => j.id === id) ?? null;
}

